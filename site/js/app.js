/* --------------------------------------------------------------------------
   <e-chart> — wraps an ECharts instance, handles resize + option updates.
   -------------------------------------------------------------------------- */
const EChart = {
  props: {
    option: { type: Object, required: true },
    height: { type: Number, default: 320 },
  },
  setup(props) {
    const el = ref(null);
    const chart = shallowRef(null);
    let ro = null;

    const render = () => {
      if (!chart.value) return;
      chart.value.setOption(props.option, true);
    };

    onMounted(() => {
      chart.value = echarts.init(el.value, null, { renderer: 'canvas' });
      render();
      ro = new ResizeObserver(() => chart.value && chart.value.resize());
      ro.observe(el.value);
    });

    onBeforeUnmount(() => {
      if (ro) ro.disconnect();
      if (chart.value) chart.value.dispose();
    });

    watch(() => props.option, render, { deep: true });

    return { el };
  },
  template: `<div ref="el" class="echart" :style="{ height: height + 'px', width: '100%' }"></div>`,
};

